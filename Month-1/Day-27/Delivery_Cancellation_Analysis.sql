-- 1. جدول العملاء (Customers)
CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    customer_name NVARCHAR(100) NOT NULL,
    city NVARCHAR(50) NOT NULL,
    join_date DATE NOT NULL
);

-- 2. جدول المطاعم (Restaurants)
CREATE TABLE restaurants (
    restaurant_id INT PRIMARY KEY,
    restaurant_name NVARCHAR(100) NOT NULL,
    cuisine_type NVARCHAR(50) NOT NULL,
    city NVARCHAR(50) NOT NULL
);

-- 3. جدول السائقين / الكباتن (Drivers)
CREATE TABLE drivers (
    driver_id INT PRIMARY KEY,
    driver_name NVARCHAR(100) NOT NULL,
    vehicle_type NVARCHAR(50) NOT NULL,
    city NVARCHAR(50) NOT NULL,
    rating DECIMAL(2, 1) CHECK (rating BETWEEN 1.0 AND 5.0)
);

-- 4. جدول الطلبات الرئيسي (Orders)
CREATE TABLE orders (
    order_id INT PRIMARY KEY,
    customer_id INT FOREIGN KEY REFERENCES customers(customer_id),
    restaurant_id INT FOREIGN KEY REFERENCES restaurants(restaurant_id),
    driver_id INT FOREIGN KEY REFERENCES drivers(driver_id),
    order_date DATETIME NOT NULL,
    order_amount DECIMAL(10, 2) NOT NULL,
    status NVARCHAR(20) CHECK (status IN (N'مكتمل', N'ملغي')),
    cancellation_reason NVARCHAR(150) NULL,
    cancelled_by NVARCHAR(20) NULL CHECK (cancelled_by IN (N'العميل', N'المطعم', N'السائق', NULL))
);

-- 5. جدول الشكاوى (Complaints)
CREATE TABLE complaints (
    complaint_id INT PRIMARY KEY,
    order_id INT FOREIGN KEY REFERENCES orders(order_id),
    complaint_type NVARCHAR(100) NOT NULL,
    complaint_status NVARCHAR(30) CHECK (complaint_status IN (N'مفتوحة', N'قيد المعالجة', N'مغلقة'))
);

