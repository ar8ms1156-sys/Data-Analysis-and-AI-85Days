-- 1. حساب نسبة الإلغاء الكلية، ومعدل نجاح الطلبات، وإجمالي الخسائر المالية
select COUNT(*) as total_orders,
sum(case when status = N'مكتمل' then 1 else 0 end ) as completed_orders ,
sum(case when status = N'ملغي' then 1 else 0 end ) as cancelled_orders ,
concat(sum(case when status = N'ملغي' then order_amount else 0 end ),'  SAR' ) as total_lost_revenue ,
concat(cast( sum(case when status = N'ملغي' then 1 else 0 end ) *100 / count(*) as decimal (5,2)) , ' %' ) as cancellation_rate_Percentage 
from orders ;

-- 2. تحليل معدلات الإلغاء والخسائر المالية المترتبة عليها حسب كل مدينة
select c.city ,
count(o.order_id) as Total_orders ,
concat(sum(case when status = N'ملغي' then o.order_amount else 0 end ),'  SAR' ) as city_lost_revenue ,
concat(cast( sum(case when o.status = N'ملغي' then 1 else 0 end ) *100 / count(o.order_id) as decimal (5,2)) , ' %' ) as city_cancellation_rate
from orders o
join customers c on o.customer_id = c.customer_id
group by c.city
order by  city_cancellation_rate desc

-- 3. تصنيف الأسباب الرئيسية للإلغاء وحجم الخسائر والجهة المتسببة
select cancellation_reason ,
cancelled_by ,
count (*) as cancelled_orders_count ,
concat(sum(order_amount),'SAR') as Total_lost_Amount ,
concat(Cast(count(*) * 100 / ( select count(*) from orders where status = N'ملغي') as decimal(5,2)),'  %' ) as percentage_of_total_cancellation
from orders
where status = N'ملغي'
group by cancellation_reason , cancelled_by 
order by cancelled_orders_count desc ;

