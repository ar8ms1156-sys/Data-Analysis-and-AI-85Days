select  CustomerID , CustomerName ,  City , CONCAT( TotalSpending , '  SAR ') as TOTALSPENDING , NumberOfOrders , 
 
 -- 1. الترتيب حسب الإنفاق داخل كل مدينة
DENSE_RANK() over( Partition by City order by TotalSpending desc ) as Spending_Rank ,

  -- 2. الترتيب حسب الولاء (عدد الطلبات) داخل كل مدينة

  DENSE_RANK() over( Partition by City order by NumberOfOrders desc ) as Loyalty_Rank
  from SaudiCustomers
  order by City ,  Spending_Rank , Loyalty_Rank
 