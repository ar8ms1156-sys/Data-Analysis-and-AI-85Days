-- 1) أكثر 5 المدن السعودية توليداً للمبيعات وإجمالي الإيرادات في المتجر
select Top 5 c.City as [المدينة], count ( o.OrderID) as [عدد الطلبات] ,CONCAT(sum ( o.TotalAmountSAR ) , '  SAR' )  as [اجمالي المبيعات بالريال ] from Customers c
inner join Orders o 
on c.CustomerID = o.CustomerID
group by c.City
order by sum ( o.TotalAmountSAR ) desc ;

-- 2) تقرير تجميعي لتوزيع حجم السلة الشرائية (Order Value Segmentation) وإجمالي إيرادات كل فئة
SELECT 
    CASE 
        WHEN o.TotalAmountSAR >= 2500 THEN N'طلب كبير (High Value)'
        WHEN o.TotalAmountSAR >= 1000 THEN N'طلب متوسط (Mid Value)'
        ELSE N'طلب صغير (Low Value)'
    END AS [فئة الطلب],
    COUNT(o.OrderID) AS [عدد الطلبات],
    CONCAT(SUM(o.TotalAmountSAR), '  SAR') AS [إجمالي مبيعات الفئة]
FROM Orders o
GROUP BY 
    CASE 
        WHEN o.TotalAmountSAR >= 2500 THEN N'طلب كبير (High Value)'
        WHEN o.TotalAmountSAR >= 1000 THEN N'طلب متوسط (Mid Value)'
        ELSE N'طلب صغير (Low Value)'
    END
ORDER BY SUM(o.TotalAmountSAR) DESC;

-- 3) تحديد العملاء الأكثر إنفاقاً (VIP Customers) الذين تجاوزت مشترياتهم 4000 ريال
select
    c.CustomerID AS [رقم العميل],
    c.CustomerName AS [اسم العميل],
    c.City AS [المدينة],
    CONCAT(o.TotalAmountSAR, '  SAR') AS [إجمالي المشتريات]
FROM Customers c
INNER JOIN Orders o 
    ON c.CustomerID = o.CustomerID
WHERE o.TotalAmountSAR >= 4000
ORDER BY o.TotalAmountSAR DESC;

-- 4) تحليل متوسط قيمة المبيعات لكل مدينة ومقارنتها بالمتوسط العام لمبيعات المتجر باستعمال Subquery
select c.City as [المدينة] , count ( o.OrderID ) as [عدد الطلبات] ,CONCAT ( CAST ( AVG ( o.TotalAmountSAR ) as decimal (10,2)) ,'  SAR' ) as [متوسط قيمة الطلب] ,  CONCAT ( Sum ( o.TotalAmountSAR ) , '  SAR' ) as [اجمالي المبيعات] from Customers c 
inner join Orders o 
on c.CustomerID = o.CustomerID 
group by c.City 
having avg ( o.TotalAmountSAR ) > ( Select avg ( TotalAmountSAR ) from Orders ) 
order by AVG ( o.TotalAmountSAR ) desc ;

-- 5) تصنيف العملاء إلى شرائح تسويقية (VIP, High, Medium, Low) بناءً على إجمالي الإنفاق باستعمال CASE WHEN
SELECT 
    CASE 
        WHEN o.TotalAmountSAR >= 4000 THEN 'VIP Customer'
        WHEN o.TotalAmountSAR >= 2500 THEN 'High Spender'
        WHEN o.TotalAmountSAR >= 1000 THEN 'Medium Spender'
        ELSE 'Low Spender'
    END AS [شريحة العميل],
    COUNT(c.CustomerID) AS [عدد العملاء],
    CONCAT(CAST(SUM(o.TotalAmountSAR) AS DECIMAL(10,2)), ' SAR') AS [إجمالي مبيعات الشريحة]
FROM Customers c
INNER JOIN Orders o 
    ON c.CustomerID = o.CustomerID
GROUP BY 
    CASE 
        WHEN o.TotalAmountSAR >= 4000 THEN 'VIP Customer'
        WHEN o.TotalAmountSAR >= 2500 THEN 'High Spender'
        WHEN o.TotalAmountSAR >= 1000 THEN 'Medium Spender'
        ELSE 'Low Spender'
    END
ORDER BY 
    SUM(o.TotalAmountSAR) DESC;